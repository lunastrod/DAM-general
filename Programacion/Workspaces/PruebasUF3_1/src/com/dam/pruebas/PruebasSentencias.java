package com.dam.pruebas;

public class PruebasSentencias {
	public static void main(String[] args) {
		int a =51;
		int b=5;
		double c=3;
		double d=7;
		int resultado;
		resultado=a+b;
		System.out.println(a+"+"+b+"="+resultado);
		resultado=a-b;
		System.out.println(a+"-"+b+"="+resultado);
		resultado=a*b;
		System.out.println(a+"x"+b+"="+resultado);
		resultado=a/b;
		System.out.println(a+"/"+b+"="+resultado);
		System.out.println(c+"/"+d+"="+c/d);
		resultado=a%b;//resto de division
		System.out.println(a+"%"+b+"="+resultado);
	}
}
